using System.Collections.Concurrent;
using System.Text;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using PrintBit.Shared.Configurations;

namespace PrintBit.Infrastructure.Windows.Scanning;

public sealed class StubScannerService : IScannerService
{
    private readonly ILogger<StubScannerService> _logger;
    private readonly ScannerSettings _settings;
    private readonly ConcurrentDictionary<string, CancellationTokenSource> _activeScans = new();

    public StubScannerService(ILogger<StubScannerService> logger, IOptions<ScannerSettings> settings)
    {
        _logger = logger;
        _settings = settings.Value;
    }

    public Task<ScannerRuntimeStatus> GetStatusAsync(CancellationToken cancellationToken = default)
    {
        return Task.FromResult(new ScannerRuntimeStatus
        {
            Connected = true,
            Adapter = "stub",
            Driver = "stub",
            DeviceName = "Stub Scanner (Dev Fallback)",
            PreferredName = _settings.PreferredScannerName,
            Capabilities = new ScannerCapabilities { Available = true },
            UsingStub = true,
            LastCheckedAt = DateTime.UtcNow,
            LastError = null
        });
    }

    public Task<ScannerCapabilities> ProbeCapabilitiesAsync(CancellationToken cancellationToken = default)
    {
        return Task.FromResult(new ScannerCapabilities
        {
            Available = true,
            Sources = ["flatbed", "adf"],
            ColorModes = ["colored", "grayscale"],
            DpiOptions = [150, 300, 600],
            Duplex = false
        });
    }

    public async Task<ScanResult> ExecuteScanAsync(ScanRequest request, CancellationToken cancellationToken = default)
    {
        var targetDir = string.IsNullOrWhiteSpace(request.OutputDir)
            ? Path.GetFullPath(_settings.ScanOutputDir)
            : Path.GetFullPath(request.OutputDir);

        Directory.CreateDirectory(targetDir);

        var ext = request.Format.ToLowerInvariant() switch
        {
            "jpg" => "jpg",
            "png" => "png",
            _ => "pdf"
        };

        var fileName = $"stub-scan-{DateTimeOffset.UtcNow.ToUnixTimeMilliseconds()}.{ext}";
        var outputPath = Path.Combine(targetDir, fileName);

        using var cts = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
        _activeScans[request.RequestId] = cts;

        try
        {
            _logger.LogInformation("[STUB-SCAN] Starting simulated scan job {requestId} -> {path}", request.RequestId, outputPath);
            await Task.Delay(2000, cts.Token);

            // Write valid mock image/pdf content so PDF.js and SumatraPDF can render and print it
            if (ext == "pdf")
            {
                WriteMockPdf(outputPath, request);
            }
            else
            {
                WriteMockImage(outputPath, request, ext);
            }

            _logger.LogInformation("[STUB-SCAN] Completed simulated scan job {requestId}", request.RequestId);
            return new ScanResult
            {
                Success = true,
                OutputPath = outputPath,
                PageCount = 1,
                Format = ext
            };
        }
        catch (OperationCanceledException)
        {
            _logger.LogWarning("[STUB-SCAN] Scan job {requestId} cancelled", request.RequestId);
            if (File.Exists(outputPath))
            {
                File.Delete(outputPath);
            }
            return new ScanResult
            {
                Success = false,
                ErrorCode = "CANCELLED",
                ErrorMessage = "Scan was cancelled by user or timeout"
            };
        }
        finally
        {
            _activeScans.TryRemove(request.RequestId, out _);
        }
    }

    public Task<bool> CancelScanAsync(string requestId)
    {
        if (_activeScans.TryGetValue(requestId, out var cts))
        {
            cts.Cancel();
            return Task.FromResult(true);
        }
        return Task.FromResult(false);
    }

    private static void WriteMockPdf(string outputPath, ScanRequest request)
    {
        var textLines = new[]
        {
            "PrintBit Virtual Scanner Document",
            "---------------------------------",
            $"Request ID:  {request.RequestId}",
            $"Timestamp:   {DateTime.Now:yyyy-MM-dd HH:mm:ss}",
            $"Paper Size:  {request.PaperSize ?? "A4"}",
            $"Color Mode:  {request.ColorMode}",
            $"Resolution:  {request.Dpi} DPI",
            $"Scan Source: {request.Source}",
            "---------------------------------",
            "This is a valid virtual scan test document generated by PrintBit.HardwareService.",
            "You can preview this file in PDF.js and print it to virtual printers."
        };

        var sb = new StringBuilder();
        sb.AppendLine("BT");
        sb.AppendLine("/F1 18 Tf");
        sb.AppendLine("50 780 Td");
        sb.AppendLine($"({EscapePdf(textLines[0])}) Tj");
        sb.AppendLine("/F1 11 Tf");
        for (int i = 1; i < textLines.Length; i++)
        {
            sb.AppendLine("0 -20 Td");
            sb.AppendLine($"({EscapePdf(textLines[i])}) Tj");
        }
        sb.AppendLine("ET");

        var streamBytes = Encoding.ASCII.GetBytes(sb.ToString());

        using var fs = new FileStream(outputPath, FileMode.Create, FileAccess.Write, FileShare.None);
        using var writer = new StreamWriter(fs, Encoding.ASCII);

        var offsets = new List<long>();
        writer.Write("%PDF-1.4\n");
        writer.Flush();

        // 1 0 obj: Catalog
        offsets.Add(fs.Position);
        writer.Write("1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n");
        writer.Flush();

        // 2 0 obj: Pages
        offsets.Add(fs.Position);
        writer.Write("2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n");
        writer.Flush();

        // 3 0 obj: Page
        offsets.Add(fs.Position);
        writer.Write("3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>\nendobj\n");
        writer.Flush();

        // 4 0 obj: Font
        offsets.Add(fs.Position);
        writer.Write("4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n");
        writer.Flush();

        // 5 0 obj: Content Stream
        offsets.Add(fs.Position);
        writer.Write($"5 0 obj\n<< /Length {streamBytes.Length} >>\nstream\n");
        writer.Flush();
        fs.Write(streamBytes, 0, streamBytes.Length);
        writer.Write("\nendstream\nendobj\n");
        writer.Flush();

        // xref
        var xrefOffset = fs.Position;
        writer.Write("xref\n0 6\n0000000000 65535 f \n");
        foreach (var offset in offsets)
        {
            writer.Write($"{offset:D10} 00000 n \n");
        }
        writer.Write($"trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n{xrefOffset}\n%%EOF\n");
        writer.Flush();
    }

    private static void WriteMockImage(string outputPath, ScanRequest request, string format)
    {
        using var bmp = new System.Drawing.Bitmap(595, 842);
        using var g = System.Drawing.Graphics.FromImage(bmp);
        g.Clear(System.Drawing.Color.White);

        using var pen = new System.Drawing.Pen(System.Drawing.Color.Navy, 3);
        g.DrawRectangle(pen, 20, 20, 555, 802);

        using var titleFont = new System.Drawing.Font("Arial", 18, System.Drawing.FontStyle.Bold);
        using var titleBrush = new System.Drawing.SolidBrush(System.Drawing.Color.Navy);
        g.DrawString("PrintBit Virtual Scanner", titleFont, titleBrush, new System.Drawing.PointF(40, 50));

        using var bodyFont = new System.Drawing.Font("Arial", 12);
        using var bodyBrush = new System.Drawing.SolidBrush(System.Drawing.Color.Black);
        var info = $"Simulated Scan Result\n\nRequest ID: {request.RequestId}\nSource: {request.Source}\nColor Mode: {request.ColorMode}\nDPI: {request.Dpi}\nTimestamp: {DateTime.Now:yyyy-MM-dd HH:mm:ss}";
        g.DrawString(info, bodyFont, bodyBrush, new System.Drawing.PointF(40, 100));

        var imgFormat = format.Equals("jpg", StringComparison.OrdinalIgnoreCase) || format.Equals("jpeg", StringComparison.OrdinalIgnoreCase)
            ? System.Drawing.Imaging.ImageFormat.Jpeg
            : System.Drawing.Imaging.ImageFormat.Png;

        bmp.Save(outputPath, imgFormat);
    }

    private static string EscapePdf(string text)
    {
        return text.Replace("\\", "\\\\").Replace("(", "\\(").Replace(")", "\\)");
    }
}